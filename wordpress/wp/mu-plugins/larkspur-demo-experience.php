/**
 * The REST route `request_consultation` posts to. Stores the lead as a
 * private custom post so it is reviewable the same way any other content on
 * this demo is (`wp post list --post_type=bmai_lead`), never emailed
 * anywhere and never exposed by any public route.
 *
 * @return void
 */
function bmai_register_consultation_cpt() {
	register_post_type(
		'bmai_lead',
		array(
			'label'    => __( 'Consultation requests', 'busymate-ai' ),
			'public'   => false,
			'show_ui'  => false,
			'supports' => array( 'title', 'editor', 'custom-fields' ),
		)
	);
}
add_action( 'init', 'bmai_register_consultation_cpt' );

/**
 * @return void
 */
function bmai_register_consultation_route() {
	register_rest_route(
		'busymate/v1',
		'/consultation',
		array(
			'methods'             => 'POST',
			'permission_callback' => '__return_true',
			'callback'            => 'bmai_handle_consultation_request',
		)
	);
}
add_action( 'rest_api_init', 'bmai_register_consultation_route' );

/**
 * @param WP_REST_Request $request The mint request.
 * @return WP_REST_Response
 */
function bmai_handle_consultation_request( $request ) {
	$name    = sanitize_text_field( (string) $request->get_param( 'name' ) );
	$email   = sanitize_email( (string) $request->get_param( 'email' ) );
	$project = sanitize_textarea_field( (string) $request->get_param( 'project' ) );

	if ( '' === $name && '' === $email && '' === $project ) {
		return new WP_REST_Response( array( 'ok' => false, 'detail' => 'Tell me your name and what you\'re planning and I\'ll start the request.' ), 200 );
	}

	$user     = is_user_logged_in() ? wp_get_current_user() : null;
	$post_id  = wp_insert_post(
		array(
			'post_type'    => 'bmai_lead',
			'post_status'  => 'private',
			'post_title'   => $name ? $name : ( $user ? $user->display_name : 'Anonymous visitor' ),
			'post_content' => $project,
			'post_author'  => 1,
		)
	);
	if ( is_wp_error( $post_id ) || ! $post_id ) {
		return new WP_REST_Response( array( 'ok' => false, 'detail' => 'Could not save the request — please try again.' ), 200 );
	}
	update_post_meta( $post_id, 'email', $email );
	if ( $user ) {
		update_post_meta( $post_id, 'wp_user_id', $user->ID );
	}
	return new WP_REST_Response(
		array(
			'ok'        => true,
			'reference' => 'LS-' . $post_id,
		),
		200
	);
}

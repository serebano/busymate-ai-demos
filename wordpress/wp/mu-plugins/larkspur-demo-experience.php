/**
 * A signed-in visitor's display name, exposed on <html> so the page-tools JS
 * (running in the visitor's own session) can read it without another
 * round-trip — the same shape woo's `data-fernweh-customer` uses.
 *
 * @param string $output The existing language-attributes string.
 * @return string
 */
function bmai_language_attributes( $output ) {
	if ( is_user_logged_in() ) {
		$user   = wp_get_current_user();
		$output .= sprintf( ' data-larkspur-customer="%s"', esc_attr( $user->display_name ) );
	}
	return $output;
}
add_filter( 'language_attributes', 'bmai_language_attributes' );

/**
 * WebMCP page tools for this content site (busymate-devtools#2969, program
 * §3.2/§3.5 — memory `webmcp-adopt-everywhere`): read-only service/contact
 * lookups plus one consequential action (`request_consultation`), which
 * calls this plugin's OWN REST route below — so the tool's logic has one
 * source of truth, same as the runbook's full-feature-demo standard.
 *
 * Printed on the front end only, deferred until `window.BusymateAI.
 * registerPageTools` exists (the embed script itself loads deferred).
 *
 * @return void
 */
function bmai_enqueue_page_tools() {
	if ( is_admin() ) {
		return;
	}
	wp_register_script( 'bmai-page-tools', false, array(), '1.0.0', true );
	wp_enqueue_script( 'bmai-page-tools' );
	wp_add_inline_script( 'bmai-page-tools', bmai_page_tools_js() );
}
add_action( 'wp_enqueue_scripts', 'bmai_enqueue_page_tools', 20 );

/**
 * Core's own `core/cover` block stylesheet (the position/object-fit rules
 * that make its background image fill the block instead of rendering as a
 * plain inline `<img>` behind the dim overlay) is not being enqueued on this
 * install — `wp-block-button`/`gallery`/`heading`/`image`/`paragraph`/
 * `columns` all load their per-block stylesheet on this theme, `cover` alone
 * does not (seen live on the hero: the photo loads at 200 but paints as a
 * flat grey box). Rather than chase why core's own enqueue skips exactly one
 * block on this host, print the same core rule the missing stylesheet would
 * have carried — small, scoped to the block's own classnames, and dropped
 * the moment the real stylesheet starts loading (an extra copy of the same
 * rule is harmless).
 *
 * @return void
 */
function bmai_cover_block_style_fallback() {
	if ( is_admin() ) {
		return;
	}
	echo '<style id="bmai-cover-fallback">'
		. '.wp-block-cover{position:relative;overflow:hidden;display:flex}'
		. '.wp-block-cover__image-background,.wp-block-cover__video-background{position:absolute;top:0;left:0;width:100%;height:100%;object-fit:cover}'
		. '.wp-block-cover__background{position:absolute;inset:0}'
		. '.wp-block-cover__inner-container{position:relative;width:100%;z-index:1;color:inherit;margin:auto 0}'
		. '</style>' . "\n";
}
add_action( 'wp_head', 'bmai_cover_block_style_fallback', 20 );


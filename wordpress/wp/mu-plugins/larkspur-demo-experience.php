const LARKSPUR_DEMO_CUSTOMER_EMAIL = 'jordan@wordpress.demo.busymate.ai';
const LARKSPUR_SIGNIN_PATH         = '/larkspur-demo-signin';
/**
 * The hosted-assistant origins the sign-in redirect may return a visitor to,
 * besides this site itself — same two-origin shape as woo's
 * `FERNWEH_HOSTED_ORIGINS` and for the same reason: a click from the platform's
 * OWN hosted chat page (`busymate.ai/support/larkspur`, or this workspace's
 * `larkspur.busymate.ai`) has to come back to whichever one it left from, or
 * the token never reaches the frame that asked for it.
 */
const LARKSPUR_HOSTED_ORIGINS = 'https://larkspur.busymate.ai,https://busymate.ai';

/*
 * ── The provided customer — the identity-provider LOGIN endpoint ───────────
 * Half two of the identity handoff (half one is the `busymate-ai` plugin's
 * own getIdentity, which only works once a visitor is ALREADY logged in).
 * This is the redirect the tenant identity provider's `login_url` points at:
 * it signs the visitor in as the ONE throwaway demo customer, mints the same
 * ES256 launch proof the plugin's own /wp-json/busymate/v1/launch route
 * mints, and hands it back in the URL FRAGMENT so it never touches a server
 * log. wp-login.php stays 404 to the public (nginx hardening) — this is the
 * only way in, and it can only ever sign in the one named account.
 *
 * @return void
 */
function bmai_demo_signin() {
	if ( is_admin() ) {
		return;
	}
	$uri  = isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : '';
	$path = is_string( $uri ) ? wp_parse_url( $uri, PHP_URL_PATH ) : '';
	if ( LARKSPUR_SIGNIN_PATH !== untrailingslashit( (string) $path ) ) {
		return;
	}

	$user = get_user_by( 'email', LARKSPUR_DEMO_CUSTOMER_EMAIL );
	if ( ! $user ) {
		status_header( 503 );
		header( 'Content-Type: application/json; charset=utf-8' );
		echo wp_json_encode( array( 'error' => 'demo_customer_missing' ) );
		exit;
	}

	wp_set_current_user( $user->ID );
	wp_set_auth_cookie( $user->ID, false, true );

	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- a navigation entry point, not a state change beyond this demo session.
	$requested = isset( $_GET['return_to'] ) ? esc_url_raw( wp_unslash( $_GET['return_to'] ) ) : '';
	$target    = bmai_allowed_return_to( $requested );

	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- this is the platform's one-time launch nonce, not a WordPress form nonce.
	$asked    = isset( $_GET['bmai_nonce'] ) ? sanitize_text_field( wp_unslash( $_GET['bmai_nonce'] ) ) : '';
	$nonce    = preg_match( '/^[A-Za-z0-9_-]{32,200}$/', $asked ) ? $asked : '';
	$fragment = bmai_launch_fragment( $user->ID, $nonce );
	if ( $fragment ) {
		$target .= ( false === strpos( $target, '#' ) ? '#' : '&' ) . $fragment;
	}

	header( 'Cache-Control: no-store' );
	header( 'Referrer-Policy: no-referrer' );
	wp_redirect( $target, 303 ); // phpcs:ignore WordPress.Security.SafeRedirect.wp_redirect_wp_redirect -- the target is already pinned to home_url below.
	exit;
}
add_action( 'init', 'bmai_demo_signin', 2 );

/**
 * The EXACT `return_to`, when its origin is this site or the platform;
 * the front page otherwise. Compared on the parsed ORIGIN, never a prefix.
 *
 * @param string $requested The raw `return_to` as it arrived.
 * @return string
 */
function bmai_allowed_return_to( $requested ) {
	$home = home_url( '/' );
	if ( ! $requested ) {
		return $home;
	}
	$parts = wp_parse_url( $requested );
	if ( ! is_array( $parts ) || empty( $parts['scheme'] ) || empty( $parts['host'] ) ) {
		return $home;
	}
	if ( 'https' !== strtolower( $parts['scheme'] ) || ! empty( $parts['user'] ) || ! empty( $parts['pass'] ) ) {
		return $home;
	}
	$origin  = 'https://' . strtolower( $parts['host'] ) . ( empty( $parts['port'] ) ? '' : ':' . $parts['port'] );
	$allowed = array_merge(
		array( untrailingslashit( home_url() ) ),
		explode( ',', LARKSPUR_HOSTED_ORIGINS )
	);
	return in_array( $origin, $allowed, true ) ? $requested : $home;
}

/**
 * The launch proof, signed by the same key and claim set the `busymate-ai`
 * plugin's own /launch route uses (`busymate_ai_launch_claims`, filtered
 * below to add the two DISPLAY claims a greeting/order-style flow reads).
 *
 * @param int    $user_id The signed-in user.
 * @param string $nonce   The nonce the caller asked to have echoed; '' mints one.
 * @return string The URL fragment, or '' when identity is unavailable.
 */
function bmai_launch_fragment( $user_id, $nonce = '' ) {
	if ( ! class_exists( 'Bmai_Keys' ) || ! defined( 'BMAI_TENANT_ID' ) ) {
		return '';
	}
	if ( ! $nonce ) {
		$nonce = rtrim( strtr( base64_encode( random_bytes( 24 ) ), '+/', '-_' ), '=' ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_encode -- base64url, not obfuscation.
	}
	$now    = time();
	$claims = array(
		'iss'             => class_exists( 'Bmai_Rest' ) ? Bmai_Rest::issuer() : untrailingslashit( home_url() ),
		'aud'             => BMAI_AUDIENCE,
		'sub'             => (string) $user_id,
		BMAI_TENANT_CLAIM => BMAI_TENANT_ID,
		'nonce'           => $nonce,
		'jti'             => wp_generate_uuid4(),
		'iat'             => $now,
		'exp'             => $now + BMAI_TOKEN_TTL,
	);
	$claims = apply_filters( 'busymate_ai_launch_claims', $claims, $user_id );
	$token  = Bmai_Keys::sign_jwt( $claims );
	if ( is_wp_error( $token ) || ! is_string( $token ) ) {
		return '';
	}
	return 'bmai_token=' . rawurlencode( $token ) . '&bmai_nonce=' . rawurlencode( $nonce );
}

/**
 * The display claims (name/email) — same rationale as woo's identical filter:
 * an email a visitor TYPES is unverified, but one the STORE signs for its own
 * signed-in user is a verified claim, and it is only ever this one invented
 * demo mailbox on this demo's own domain.
 *
 * @param array $claims  The claim set the plugin is about to sign.
 * @param int   $user_id The signed-in user.
 * @return array
 */
function bmai_launch_display_claims( $claims, $user_id ) {
	$user = get_userdata( $user_id );
	if ( ! $user ) {
		return $claims;
	}
	$claims['name']  = $user->display_name;
	$claims['email'] = $user->user_email;
	return $claims;
}
add_filter( 'busymate_ai_launch_claims', 'bmai_launch_display_claims', 10, 2 );

/**
 * `[bmai_assistant]` — an inline chat surface using the SAME `/support/<slug>`
 * frame the floating widget's own iframe points at (embed/v1.js), just
 * mounted in the page flow instead of a corner FAB. Also registered as a
 * Gutenberg block (`busymate-ai/assistant`) below, sharing this renderer.
 *
 * @return string
 */
function bmai_assistant_shortcode() {
	$src = sprintf(
		'%s/support/%s?channel=embed&bridge=busymate-ai-v1',
		untrailingslashit( BMAI_EMBED_ORIGIN ),
		rawurlencode( BMAI_TENANT_SLUG )
	);
	return sprintf(
		'<div class="bmai-inline-assistant" style="margin:2em auto;max-width:480px;border:1px solid #e2e2e2;border-radius:16px;overflow:hidden;box-shadow:0 8px 30px rgba(0,0,0,.08)">'
			. '<iframe src="%1$s" title="%2$s" loading="lazy" referrerpolicy="strict-origin-when-cross-origin" allow="tools; microphone; autoplay" sandbox="allow-scripts allow-forms allow-same-origin" style="display:block;width:100%%;height:640px;border:0;background:#111"></iframe>'
			. '</div>',
		esc_url( $src ),
		esc_attr__( 'AI assistant', 'busymate-ai' )
	);
}
add_shortcode( 'bmai_assistant', 'bmai_assistant_shortcode' );

/**
 * The same shortcode as a Gutenberg block — no build step: a dynamic,

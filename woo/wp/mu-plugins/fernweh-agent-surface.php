/**
 * Open Graph and Twitter cards. The theme prints none, so a link to this store
 * shared anywhere — and every reader that takes og:* as the page's summary —
 * saw nothing at all. Built from what the page really is: a product's own name,
 * price and image on a product page, the shop's on everything else.
 *
 * @return void
 */
function fernweh_open_graph() {
	$title = wp_get_document_title();
	$url   = home_url( add_query_arg( array() ) );
	$image = FERNWEH_ORIGIN . '/img/og.png';
	$type  = 'website';
	$desc  = 'Fernweh Supply Co. — small-batch packs, merino layers, bottles and notebooks, made in Leipzig. '
		. 'A Busymate AI demonstration store: nothing is dispatched and no payment is taken.';

	// The shop IS a WordPress page, and it is the front page, so this arm has to
	// come first: `is_page()` is true here and `get_the_excerpt()` inside a
	// product loop returns the FIRST PRODUCT's summary, which described the whole
	// store as a merino crew.
	if ( is_front_page() || ( function_exists( 'is_shop' ) && is_shop() ) ) {
		$type  = 'website';
		$title = 'Fernweh Supply Co. — small-batch gear for the long way round';
	} elseif ( function_exists( 'is_product' ) && is_product() ) {
		$product = function_exists( 'wc_get_product' ) ? wc_get_product( get_the_ID() ) : null;
		if ( $product ) {
			$type  = 'product';
			$title = wp_strip_all_tags( $product->get_name() );
			$short = wp_strip_all_tags( $product->get_short_description() );
			$desc  = $short ? $short : $desc;
			$src   = wp_get_attachment_image_url( $product->get_image_id(), 'large' );
			if ( $src ) {
				$image = $src;
			}
		}
	} elseif ( is_page() ) {
		$type    = 'article';
		$excerpt = wp_strip_all_tags( get_the_excerpt() );
		if ( $excerpt ) {
			$desc = $excerpt;
		}
	}

	$tags = array(
		'og:type'             => $type,
		'og:site_name'        => 'Fernweh Supply Co.',
		'og:title'            => $title,
		'og:description'      => $desc,
		'og:url'              => $url,
		'og:image'            => $image,
		'og:locale'           => 'en_US',
		'twitter:card'        => 'summary_large_image',
		'twitter:title'       => $title,
		'twitter:description' => $desc,
		'twitter:image'       => $image,
	);
	foreach ( $tags as $name => $value ) {
		if ( ! $value ) {
			continue;
		}
		$attr = 0 === strpos( $name, 'og:' ) ? 'property' : 'name';
		printf(
			'<meta %1$s="%2$s" content="%3$s">' . "\n",
			esc_attr( $attr ),
			esc_attr( $name ),
			esc_attr( wp_html_excerpt( $value, 300, '…' ) )
		);
	}
}
add_action( 'wp_head', 'fernweh_open_graph', 3 );

/**
 * The requested path, without the query string.
 *
 * @return string
 */
function fernweh_request_path() {
	$uri = isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : '';
	if ( ! is_string( $uri ) || '' === $uri ) {
		return '';
	}
	$path = wp_parse_url( $uri, PHP_URL_PATH );
	return is_string( $path ) ? $path : '';
}

/**
 * Answer the agent-readable paths before WordPress routes anything.
 *
 * @return void
 */
function fernweh_serve_agent_files() {
	if ( is_admin() ) {
		return;
	}
	$path   = fernweh_request_path();
	$routes = fernweh_static_routes();

	if ( '/robots.txt' === $path ) {
		fernweh_send( fernweh_robots(), 'text/plain; charset=utf-8', 'public, max-age=600' );
	}
	if ( '/sitemap.xml' === $path ) {
		fernweh_send( fernweh_sitemap(), 'application/xml; charset=utf-8', 'public, max-age=600' );
	}
	if ( ! isset( $routes[ $path ] ) ) {
		return;
	}
	list( $file, $type ) = $routes[ $path ];
	$full                = FERNWEH_DATA_DIR . '/' . $file;
	if ( ! is_readable( $full ) ) {
		status_header( 404 );
		header( 'Content-Type: application/json; charset=utf-8' );
		header( 'Cache-Control: no-store' );
		echo wp_json_encode( array( 'error' => 'agent_file_missing', 'path' => $path ) );
		exit;
	}
	// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- a local generated file, not a remote fetch.
	fernweh_send( file_get_contents( $full ), $type, 'public, max-age=300, stale-while-revalidate=3600' );
}
add_action( 'init', 'fernweh_serve_agent_files', 1 );

/**
 * Emit one body and stop.
 *
 * @param string $body    The response body.
 * @param string $type    Content type.
 * @param string $cache   Cache-Control value.
 * @return void
 */
function fernweh_send( $body, $type, $cache ) {
	status_header( 200 );
	header( 'Content-Type: ' . $type );
	header( 'Cache-Control: ' . $cache );
	header( 'Access-Control-Allow-Origin: *' );
	header( 'X-Content-Type-Options: nosniff' );
	echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- pre-rendered generated content.
	exit;
}

/**
 * robots.txt — every AI crawler named explicitly, and a Sitemap line that
 * points at a sitemap this site actually serves. WordPress's own virtual
 * robots.txt names none of them and pointed at /wp-sitemap.xml, which 404s here.
 *
 * @return string
 */
function fernweh_robots() {
	$agents = array( 'GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-User', 'anthropic-ai', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended', 'CCBot', 'Bytespider', 'meta-externalagent' );
	$out    = "# Fernweh Supply Co. — a Busymate AI demonstration store.\n"
		. "# Everything here is readable by an agent on purpose: see /llms.txt and /agents.json.\n\n"
		. "User-agent: *\n"
		. "Allow: /\n"
		. "Disallow: /cart/\n"
		. "Disallow: /checkout/\n"
		. "Disallow: /my-account/\n"
		. "Disallow: /*?add-to-cart=\n\n";
	foreach ( $agents as $agent ) {
		$out .= 'User-agent: ' . $agent . "\nAllow: /\n\n";
	}
	$out .= 'Sitemap: ' . FERNWEH_ORIGIN . "/sitemap.xml\n";
	return $out;
}

/**
 * An honest sitemap: the pages and products that are really published, each
 * with the date WordPress last modified it.
 *
 * @return string
 */
function fernweh_sitemap() {
	$urls = array( array( 'loc' => FERNWEH_ORIGIN . '/', 'mod' => '', 'pri' => '1.0' ) );

	$pages = get_posts(
		array(
			'post_type'      => 'page',
			'post_status'    => 'publish',
			'posts_per_page' => 50,
			'orderby'        => 'menu_order',
			'order'          => 'ASC',
		)
	);
	foreach ( $pages as $page ) {
		$link = get_permalink( $page );
		// The cart, checkout and account pages are a shopper's private workspace,
		// not content: robots.txt disallows them, so listing them would be a
		// sitemap contradicting the file next to it.
		if ( preg_match( '#/(cart|checkout|my-account)/#', (string) $link ) ) {
			continue;
		}
		$urls[] = array( 'loc' => $link, 'mod' => get_post_modified_time( 'c', true, $page ), 'pri' => '0.6' );
	}

	if ( function_exists( 'wc_get_products' ) ) {
		$products = wc_get_products( array( 'status' => 'publish', 'limit' => 200 ) );
		foreach ( $products as $product ) {
			$urls[] = array(
				'loc' => $product->get_permalink(),
				'mod' => $product->get_date_modified() ? $product->get_date_modified()->date( 'c' ) : '',
				'pri' => '0.8',
			);
		}
	}

	foreach ( get_terms( array( 'taxonomy' => 'product_cat', 'hide_empty' => true ) ) as $term ) {
		if ( is_wp_error( $term ) ) {
			continue;
		}
		$urls[] = array( 'loc' => get_term_link( $term ), 'mod' => '', 'pri' => '0.5' );
	}

	// The agent-readable layers are pages too, for a reader that arrives here first.
	foreach ( array( '/llms.txt', '/llms-full.txt', '/agents.json', '/webmcp-catalog.json' ) as $extra ) {
		$urls[] = array( 'loc' => FERNWEH_ORIGIN . $extra, 'mod' => '', 'pri' => '0.4' );
	}

	$xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n";
	foreach ( $urls as $url ) {
		if ( empty( $url['loc'] ) || is_wp_error( $url['loc'] ) ) {
			continue;
		}
		$xml .= "  <url>\n    <loc>" . esc_url( $url['loc'] ) . "</loc>\n";
		if ( $url['mod'] ) {
			$xml .= '    <lastmod>' . esc_html( $url['mod'] ) . "</lastmod>\n";
		}
		$xml .= '    <priority>' . esc_html( $url['pri'] ) . "</priority>\n  </url>\n";
	}
	return $xml . "</urlset>\n";
}

/**
 * The links that let a reader which never runs the page find all of the above.
 *
 * @return void
 */
function fernweh_head_links() {
	$twins = array(
		'shipping' => '/shipping.md',
		'returns'  => '/returns.md',
		'privacy'  => '/privacy.md',
		'terms'    => '/terms.md',
	);
	echo "\n<!-- This store is agent-readable on purpose. -->\n";
	echo '<link rel="webmcp-catalog" href="/webmcp-catalog.json">' . "\n";
	// #2905/C6 (corrected 2026-09-14 against a live agent-ready.dev rescan):
	// the bespoke discovery card lives at the WELL-KNOWN path — the bare
	// /agents.json path is what the real external checker reads as the
	// agentsJson v0.1.0 tool-actions manifest.
	echo '<link rel="alternate" type="application/json" href="/.well-known/agents.json" title="Agent card">' . "\n";
	echo '<link rel="describedby" href="/llms.txt">' . "\n";
	echo '<link rel="alternate" type="text/plain" href="/llms.txt" title="llms.txt">' . "\n";
	echo '<link rel="alternate" type="text/plain" href="/llms-full.txt" title="llms-full.txt">' . "\n";
	$path = untrailingslashit( fernweh_request_path() );
	foreach ( $twins as $slug => $md ) {
		if ( '/' . $slug === $path ) {
			echo '<link rel="alternate" type="text/markdown" href="' . esc_attr( $md ) . '" title="This page as Markdown">' . "\n";
		}
	}
	if ( is_front_page() || is_shop() ) {
		echo '<link rel="alternate" type="text/markdown" href="/index.md" title="This page as Markdown">' . "\n";
	}
}
add_action( 'wp_head', 'fernweh_head_links', 2 );


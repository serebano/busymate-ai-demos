<?php
/**
 * Plugin Name: Fernweh — agent-readable surface
 * Description: Serves this demo store's six agent-readable layers (llms.txt, llms-full.txt,
 *              agents.json + its .well-known twin, webmcp-catalog.json, robots.txt, sitemap.xml),
 *              the Markdown twin of every policy page, and the page-tool bundle — all from
 *              WordPress itself.
 * Version:     1.1.0
 * Author:      Busymate AI demo playground
 *
 * WHY THIS IS A PLUGIN AND NOT A DOCROOT.
 * Every other demo on the playground is a static docroot that `scripts/deploy.sh`
 * rsyncs, and its six agent files are ordinary files nginx serves. This demo is a
 * real WordPress application in its own container: deploy.sh filters on
 * `type == "static"` and deliberately never touches it, and nginx proxies every
 * path to WordPress. So the files have to come OUT of WordPress, and dropping
 * them into the WordPress docroot is not an option either — an `index.html`
 * there would shadow `index.php` and take the shop down.
 *
 * The generated bytes therefore ship in `data/` next to this file (synced verbatim from
 * `sites/woo/public/` by sites/woo/provision.sh, which is how they stay
 * infrastructure-as-code) and this plugin answers the paths for them, on `init`
 * at priority 1 — before WordPress can canonicalise a path it does not
 * recognise into a trailing-slash redirect to an HTML page.
 *
 * `sitemap.xml` is NOT a shipped file: it is built here from the pages and
 * products that are actually published, with their real modified dates, because
 * an honest sitemap is the one the site can prove.
 *
 * @package Fernweh_Demo
 */

defined( 'ABSPATH' ) || exit;

define( 'FERNWEH_DATA_DIR', __DIR__ . '/data' );
define( 'FERNWEH_ORIGIN', 'https://woo.demo.busymate.ai' );

